"""## 10. Safe preprocessing and oversampling pipelines

Median imputation, categorical encoding (if applicable), and Logistic Regression scaling are fitted **within each training fold**. `RandomOverSampler` is inside the `imblearn` pipeline. The baseline uses an oversampling ratio of 1.0; the optimizer can compare no oversampling, 0.5 and 1.0. Validation and test records are never oversampled.
"""

def make_preprocessor(scale_numeric=False):
    numeric_steps = [("imputer", SimpleImputer(strategy="median"))]
    if scale_numeric:
        numeric_steps.append(("scaler", StandardScaler()))

    transformers = []
    if numeric_columns:
        transformers.append(("num", SkPipeline(numeric_steps), numeric_columns))
    if categorical_columns:
        transformers.append(("cat", SkPipeline([
            ("imputer", SimpleImputer(strategy="most_frequent")),
            ("onehot", OneHotEncoder(handle_unknown="ignore", sparse_output=False)),
        ]), categorical_columns))

    return ColumnTransformer(transformers=transformers, remainder="drop", sparse_threshold=0)


def build_pipeline(estimator, scale_numeric=False):
    return ImbPipeline(steps=[
        ("preprocess", make_preprocessor(scale_numeric=scale_numeric)),
        ("oversample", RandomOverSampler(
            sampling_strategy=OVERSAMPLING_RATIO,
            random_state=RANDOM_STATE,
        )),
        ("model", estimator),
    ])

print("Pipeline: preprocessing -> training-only RandomOverSampler -> classifier")
print("Categorical feature count:", len(categorical_columns))
print("Only Logistic Regression uses StandardScaler for numerical features.")

