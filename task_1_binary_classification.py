"""## 14. Hyperparameter and imbalance-strategy search

**Optimization stage.** For each classifier, sample 8 sets of reasonable hyperparameters and compare three balancing choices (`none`, `oversample_0.5`, `oversample_1.0`). Evaluate every candidate on the **same five training-only validation folds**. Collect out-of-fold positive-class probabilities and choose a threshold from 0.05 to 0.95 that maximizes pooled F1. Rank configurations by F1 (PR-AUC breaks ties).

The selected out-of-fold score is an **optimistic selection statistic**, not an unbiased test estimate. The test set remains unused by the search. Models are **not** fine-tuned with test predictions. For faster Colab runs use the default 8 samples/model; increasing `N_SEARCH_PER_MODEL` makes optimization more exhaustive and slower.
"""

SEARCH_SPACES = {
    "Logistic Regression": {
        "C": loguniform(0.03, 30.0),
        "penalty": ["l1", "l2"],
    },
    "Random Forest": {
        "n_estimators": randint(120, 320),
        "max_depth": [5, 8, 12, 16, None],
        "min_samples_leaf": randint(1, 8),
        "min_samples_split": randint(2, 14),
        "max_features": ["sqrt", 0.7, 1.0],
        "max_samples": [0.75, 0.9, None],
    },
    "Gradient Boosting": {
        "n_estimators": randint(80, 300),
        "learning_rate": loguniform(0.02, 0.2),
        "max_depth": [2, 3, 4],
        "min_samples_leaf": randint(2, 20),
        "subsample": uniform(0.72, 0.28),
        "max_features": [0.7, 0.9, None],
    },
    "LightGBM": {
        "n_estimators": randint(100, 400),
        "learning_rate": loguniform(0.02, 0.14),
        "num_leaves": randint(7, 32),
        "max_depth": [3, 4, 5, 6, -1],
        "min_child_samples": randint(8, 45),
        "reg_alpha": loguniform(0.001, 3.0),
        "reg_lambda": loguniform(0.02, 12.0),
        "colsample_bytree": uniform(0.7, 0.3),
    },
}

def optimized_pipeline(model_name, params, strategy):
    """Fresh pipeline; all preprocessing and sampling happen within training data."""
    if strategy not in BALANCE_STRATEGIES:
        raise ValueError(f"Invalid imbalance strategy: {strategy}")
    spec = MODEL_DEFINITIONS[model_name]
    model = clone(spec["estimator"]).set_params(**params)
    ratio = BALANCE_STRATEGIES[strategy]
    sampler = ("passthrough" if ratio is None else
               RandomOverSampler(sampling_strategy=ratio, random_state=RANDOM_STATE))
    return ImbPipeline([
        ("preprocess", make_preprocessor(scale_numeric=spec["scale_numeric"])),
        ("oversample", sampler),
        ("model", model),
    ])

folds = list(cv.split(X_train, y_train))
assert len(folds) == 5

def find_best_oof_threshold(labels, probabilities):
    scores = np.array([
        f1_score(labels, probabilities >= t, zero_division=0)
        for t in THRESHOLDS
    ])
    winners = np.flatnonzero(np.isclose(scores, scores.max()))
    best_idx = winners[np.argmin(np.abs(THRESHOLDS[winners] - 0.50))]
    return float(THRESHOLDS[best_idx]), float(scores[best_idx])

print("Optimization search ready:", N_SEARCH_PER_MODEL, "parameter sets x",
      len(BALANCE_STRATEGIES), "balancing options x", len(folds), "folds / model")

# Searches only X_train/y_train. No held-out test values are accessed here.
from sklearn.metrics import average_precision_score

optimization_rows = []
selected_rows = []
selected_config = {}
selected_oof = {}

for model_number, (model_name, spec) in enumerate(MODEL_DEFINITIONS.items(), 1):
    print("\n" + "=" * 72)
    print(f"OPTIMIZING {model_name} ({model_number}/{len(MODEL_DEFINITIONS)})")
    print("=" * 72)
    candidates = list(ParameterSampler(
        SEARCH_SPACES[model_name], n_iter=N_SEARCH_PER_MODEL, random_state=RANDOM_STATE
    ))
    model_results = []
    safe_name = model_name.replace(" ", "_")
    best_oof = None
    best_key = None

    for candidate_no, params in enumerate(candidates, start=1):
        for strategy in BALANCE_STRATEGIES:
            probabilities = np.full(len(X_train), np.nan, dtype=float)
            for fit_idx, val_idx in folds:
                p = optimized_pipeline(model_name, params, strategy)
                p.fit(X_train.iloc[fit_idx], y_train.iloc[fit_idx])
                classes = list(p.named_steps["model"].classes_)
                probabilities[val_idx] = p.predict_proba(X_train.iloc[val_idx])[:, classes.index(1)]
            if not np.isfinite(probabilities).all():
                raise RuntimeError(f"Missing out-of-fold predictions for {model_name}")
            threshold, pooled_f1 = find_best_oof_threshold(y_train.to_numpy(), probabilities)
            fold_f1 = [f1_score(y_train.iloc[val], probabilities[val] >= threshold,
                                zero_division=0) for _, val in folds]
            pr_auc = float(average_precision_score(y_train, probabilities))
            row = {
                "Model": model_name,
                "Candidate": candidate_no,
                "Strategy": strategy,
                "OOF_Selection_F1": pooled_f1,
                "OOF_Precision": float(precision_score(y_train, probabilities >= threshold, zero_division=0)),
                "OOF_Recall": float(recall_score(y_train, probabilities >= threshold, zero_division=0)),
                "OOF_PR_AUC": pr_auc,
                "Fold_F1_Std": float(np.std(fold_f1, ddof=1)),
                "Threshold": threshold,
                "Parameters": json.dumps(params, sort_keys=True, default=lambda o: o.item() if isinstance(o, np.generic) else str(o)),
            }
            model_results.append(row)
            key = (pooled_f1, pr_auc, -float(np.std(fold_f1, ddof=1)))
            if best_key is None or key > best_key:
                best_key = key
                best_oof = probabilities.copy()
        # Checkpoint search results after each parameter set; survives a Colab disconnect.
        checkpoint = pd.DataFrame(model_results)
        checkpoint.to_csv(OUTPUT_DIR / f"{safe_name}_optimization_search.csv", index=False)
        print(f"  parameter set {candidate_no}/{N_SEARCH_PER_MODEL} complete; "
              f"best OOF selection F1 = {best_key[0]:.4f}", flush=True)

    ranked = pd.DataFrame(model_results).sort_values(
        ["OOF_Selection_F1", "OOF_PR_AUC", "Fold_F1_Std"],
        ascending=[False, False, True]
    ).reset_index(drop=True)
    best = ranked.iloc[0].to_dict()
    selected_config[model_name] = {
        "strategy": best["Strategy"],
        "params": json.loads(best["Parameters"]),
        "threshold": float(best["Threshold"]),
        "oof_selection_f1": float(best["OOF_Selection_F1"]),
    }
    selected_oof[model_name] = best_oof
    selected_rows.append({key: value for key, value in best.items() if key != "Parameters"})
    optimization_rows.extend(model_results)
    save_json(selected_config[model_name], f"{safe_name}_selected_optimization.json")
    save_csv(pd.DataFrame({
        "Original_Row_Index": X_train.index,
        "Actual": y_train.to_numpy(),
        "OOF_Positive_Probability": best_oof,
        "OOF_Prediction": (best_oof >= float(best["Threshold"])).astype(int),
    }), f"{safe_name}_optimized_train_oof_predictions.csv")
    print(f"Selected: {best['Strategy']}, threshold={best['Threshold']:.2f}, "
          f"OOF selection F1={best['OOF_Selection_F1']:.4f}")

optimization_df = pd.DataFrame(optimization_rows)
selected_df = pd.DataFrame(selected_rows).sort_values("OOF_Selection_F1", ascending=False)
